#ifndef MOBILE_INPUT_H
#define MOBILE_INPUT_H

#include "raylib.h"
#include <stdbool.h>

// Captures raw Android touch points once per frame. A touch that begins on the
// left stick remains owned by the stick, so a second finger can still use an
// item or pause the game.
void MobileInputUpdate(bool gameplayActive, int controlMode);

// Returns one of four cardinal directions and a radial strength in 0..1.
// There is no temporal smoothing here: the current finger position is the
// source of truth for the current frame.
bool MobileGetMoveVector(Vector2 *direction, float *strength);

// Pure floating-stick geometry used by the runtime and by the desktop math
// test. If the finger exceeds maxRadius, the center follows by the excess.
void MobileSolveFloatingStick(Vector2 *center, Vector2 finger, float maxRadius,
                              Vector2 *direction, float *strength);

// Maps an arbitrary direction to its dominant horizontal or vertical axis.
Vector2 MobileCardinalizeDirection(Vector2 direction);

// Pure fixed-D-pad geometry used by runtime and desktop math tests.
void MobileSolveFixedDpad(Vector2 center, Vector2 finger, float radius,
                          Vector2 *direction, float *strength);

// Pure split-control geometry: vertical=true maps only up/down, otherwise
// only left/right.
void MobileSolveSplitControl(Vector2 center, Vector2 finger, float radius,
                             bool vertical, Vector2 *direction, float *strength);

// True for the first frame of any touch beginning inside the rectangle.
bool MobileTouchPressed(Rectangle rect);

// Wheel-compatible value generated by a vertical finger drag in menus.
float MobileGetScrollWheel(void);

// Draws a permanent resting preview or, while touched, the floating base and
// the knob at the real finger position.
void MobileDrawStick(void);

#endif // MOBILE_INPUT_H
